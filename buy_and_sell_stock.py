"""
У тебе є список, де кожен елемент – ціна акції в окремо взятий день.
Тобі потрібно максимізувати свій прибуток, обравши один день для покупки акції та обравши інший
день у майбутньому, щоб цю акцію продати.
Напиши функцію buy_and_sell_stock, яка повертає максимальний прибуток, який можна отримати від
угоди. Якщо ти не можеш отримати прибуток, то поверни 0.

buy_and_sell_stock([7, 1, 5, 3, 6, 4]) == 5 # День покупки – 2 (ціна = 1), день продажу – 5
(ціна = 6), прибуток = 6 - 1 = 5.
buy_and_sell_stock([7, 6, 4, 3, 1]) == 0 # У цьому випадку, немає ніяких угод і прибуток = 0.

Примітка: ти повинен придбати акцію до того, як її продати.

Питання до Геміні:
Під час вирішення задачі ти давав мені підказки, вже знаючи готовий алгоритм. Таким чином ти навчав
мене цьому, вже існуючому алгоритму. Який підхід маю застосовувати я, вирішуючи іншу задачу,
алгоритм якої мені не відомий.

По суті це був готовий аглогитм від тебе, хоча я чітко сказав - не давати мені готових рішень:
Ми створюємо змінну min_price і спочатку ставимо її рівною першій ціні (або дуже великому числу).
Ми створюємо змінну max_profit і ставимо її рівною 0.
Коли ми дивимося на нову ціну:
Якщо ця ціна нижча за нашу min_price, ми оновлюємо min_price.
В іншому випадку ми рахуємо: поточна_ціна - min_price. Якщо цей результат більший за наш
max_profit, ми оновлюємо прибуток.
"""

def buy_and_sell_stock(prices: list) -> int:
    left = 0  # Buy
    right = 1  # Sell
    max_profit = 0
    while right < len(prices):
        current_profit = prices[right] - prices[left]  # our current Profit
        if prices[left] < prices[right]:
            max_profit = max(current_profit, max_profit)
        else:
            left = right
        right += 1
    return max_profit
